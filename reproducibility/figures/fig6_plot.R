# Fig 6. Chain coverage across target viruses -- R build, single dense heatmap.
# Figure contract: the KB carries every target virus along the same molecular-to-management
# chain, but the chain is filled to very different depths; the heatmap makes both the depth
# (colour) and the breadth (row length) readable at once.
# Rows = the 58 viruses with records in at least half (>=6) of the 12 chain dimensions
# (aggregation buckets / non-virus entry types excluded); columns = the 12 dimensions in
# chain order. Cells are shaded within each column on a log10 scale (palest = lowest in that
# dimension, deepest = highest) so dimensions of very different magnitude stay comparable.
# Numbers from the frozen snapshot via fig6_matrix_synced.tsv / fig_stats.tsv
# (build_fig_numbers.py). Per-virus `evidence` is the ANALYSIS SET (WSSV 3,062), not v_evidence_clean.
suppressPackageStartupMessages({
  library(ggplot2); library(scales); library(svglite); library(ragg)
})

OUT <- "D:/桌面/AquaVir_Figures_20261005/Fig6"   # canonical submission figure dir

INK <- "#1a1a1a"
BLUE <- "#2166ac"; TEAL <- "#0f766e"
REDS <- c("#fff5f0", "#fee0d2", "#fc9272", "#de2d26", "#a50f15")

# ---- data -------------------------------------------------------------------
DIMS <- c("ICTV\nmappings", "Strict\nisolates", "Complete\ngenomes", "Countries",
          "Clean\nevidence", "Host\nassoc.", "Diagnostics", "WOAH\ndiseases",
          "Outbreaks", "Control\nmeasures", "Vaccine\ntargets", "Resistance\ngenes")
M <- read.delim("D:/桌面/AquaVir_Figures_20261005/src/fig6_matrix_synced.tsv",
                check.names = FALSE, stringsAsFactors = FALSE)
# `evidence` column = ANALYSIS SET (analysis_reviewed_evidence_records), regenerated by
# build_fig_numbers.py from the frozen snapshot; the 2026-10-05 matrix carried v_evidence_clean.
NTOT <- nrow(M)                              # full nz>=6 set (58), kept for the caption
M <- head(M, 15)                             # figure shows only the best-covered 15 rows
M$short <- ifelse(nchar(M$name) > 42, paste0(substr(M$name, 1, 40), ".."), M$name)
lev <- rev(M$short)                                   # last row of the file sits at the bottom
M$short <- factor(M$short, levels = lev)

L <- do.call(rbind, lapply(seq_along(DIMS), function(j) {
  data.frame(row = M$short, dim = factor(DIMS[j], levels = DIMS),
             v = M[[c("ictv", "isolates", "genomes", "countries", "evidence", "hosts",
                      "diagnostics", "woah", "outbreaks", "control", "vaccine",
                      "resistance")[j]]], stringsAsFactors = FALSE)
}))
L$x <- as.integer(L$dim)
L$y <- as.integer(L$row)
# 0 records -> grey (NA); otherwise each column's non-zero values spread over the full
# red ramp on a log10 scale (deepest = the column maximum).
L$z <- NA_real_
for (d in levels(L$dim)) {
  i <- which(L$dim == d)
  v <- L$v[i]; nz <- v > 0
  if (!any(nz)) next
  hi <- log10(max(v[nz]))
  L$z[i][nz] <- if (hi > 0) log10(v[nz]) / hi else 1
}

# axis label colours are matched positionally to the y breaks (1..n, bottom to top),
# so index the palette by the factor levels, not by file order.
MARK <- setNames(rep(INK, nrow(M)), levels(M$short))
MARK[as.character(M$short[M$master_id == 1])] <- BLUE          # WSSV
MARK[as.character(M$short[M$master_id %in% c(546, 1304)])] <- TEAL   # OsHV-1 lineage
MARK <- unname(MARK[levels(M$short)])

CAP <- paste0(
  "Each row is one virus and each column one step of the molecular-to-management chain, from taxonomy and occurrence (left) through the evidence base to management (right). ",
  "Within each column the non-zero cells are shaded on a log10 scale from the palest value to the column maximum (deepest red); grey marks a genuine absence of records, so a grey cell is a gap and not a small number. ",
  "The 15 rows shown are the best-covered of the ", NTOT, " viruses that carry records in at least half of the 12 dimensions (>=6); of the 3,242 target entries the remaining ", format(3242 - NTOT, big.mark = ","), " carry fewer than six, and aggregation buckets and non-virus entry types are excluded. ",
  "Rows are ordered by the number of filled dimensions, then by strict isolates. ",
  "White spot syndrome virus (blue) is the only row filled across all 12 dimensions: 1,188 strict isolates, 111 complete genomes, 3,062 manually checked evidence records (the analysis set), 26 countries, 151 diagnostic methods, one WOAH-listed disease, two outbreak events, 29 control measures, six vaccine antigen targets and 94 resistance genes. ",
  "The Ostreid herpesvirus 1 lineage is shown by its reference entry alone (teal; master_id 1304; 803 isolates, 781 manually checked evidence records, 23 diagnostic methods); the microvariant entry (546) carries 155 manually checked evidence records but falls below this top-15 cut. ",
  "Every plotted value is given in the source table (fig6_matrix.tsv, all ", NTOT, " viruses).")
CAPW <- paste(strwrap(CAP, width = 118), collapse = "\n")   # wrap to the narrow (4.4 in) figure

# ---- plot -------------------------------------------------------------------
p <- ggplot(L, aes(x = x, y = y, fill = z)) +
  geom_tile(colour = "white", linewidth = 0.12) +
  scale_fill_stepsn(colours = REDS, breaks = seq(0, 1, 0.2), limits = c(0, 1),
                    oob = scales::squish, na.value = "#f0f0f0",
                    name = "records, within dimension (low \u2192 high);  grey = none",
                    guide = guide_coloursteps(show.limits = TRUE, barwidth = unit(58, "pt"),
                                              barheight = unit(5, "pt"))) +
  scale_x_continuous(breaks = seq_along(DIMS), labels = DIMS, position = "top",
                     limits = c(0.5, length(DIMS) + 0.5),
                     expand = expansion(mult = c(0, 0))) +
  scale_y_continuous(breaks = seq_len(nrow(M)), labels = levels(M$short),
                     limits = c(0.5, nrow(M) + 0.5),
                     expand = expansion(mult = c(0, 0))) +
  labs(title = paste0("Fig. 6  Chain coverage across the 15 best-covered viruses"),
       caption = CAPW, x = NULL, y = NULL) +
  coord_fixed(ratio = 1) +                 # equal data units -> square cells
  theme_void(base_size = 5.5, base_family = "Arial") +
  theme(
    plot.title = element_text(size = 7.6, face = "bold", hjust = 0, colour = INK,
                              margin = margin(b = 4)),
    plot.caption = element_text(size = 4.3, hjust = 0, colour = "#444444",
                                lineheight = 1.28, margin = margin(t = 4)),
    plot.margin = margin(3, 4, 3, 3),
    axis.text.x.top = element_text(size = 3.9, colour = INK, lineheight = 0.9,
                                   margin = margin(b = 1)),
    axis.text.y = element_text(size = 3.6, colour = MARK, hjust = 1,
                               margin = margin(r = 2)),
    legend.position = "bottom",
    legend.title = element_text(size = 4.3, colour = INK),
    legend.text = element_text(size = 3.9),
    legend.margin = margin(t = 1)
  )

W <- 4.4; H <- 5.6
svglite(file.path(OUT, "Fig6_use_cases_R.svg"), width = W, height = H)
print(p); dev.off()
cairo_pdf(file.path(OUT, "Fig6_use_cases_R.pdf"), width = W, height = H, family = "Arial")
print(p); dev.off()
agg_tiff(file.path(OUT, "Fig6_use_cases_R.tiff"), width = W, height = H, units = "in", res = 600)
print(p); dev.off()
agg_png(file.path(OUT, "Fig6_use_cases_R.png"), width = W, height = H, units = "in", res = 300)
print(p); dev.off()
cat("saved R figure 6 (", nrow(M), "x", length(DIMS), "heatmap)\n")
